"""Turn scored results into a Markdown summary, LaTeX tables and figures for the paper."""

from __future__ import annotations

import math
from pathlib import Path

from .faults import FAULTS, LABELS
from .simulate import CONDITIONS

COND_NAMES = {"full": "Full logs", "noisy": "Noisy logs", "generic": "Generic logs", "metrics_only": "Metrics only"}


def pct(x: float) -> str:
    return "–" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.1f}"


def _num(x: float, spec: str) -> str:
    return "–" if x is None or math.isnan(x) else format(x, spec)


def tex_name(s: str) -> str:
    return s.replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


def write_markdown(summary: dict, path: Path) -> None:
    m = summary["methods"]
    lines = ["# Results", "", "Accuracy = the predicted root cause is correct (single-fault and control trials). "
             "95% Wilson confidence intervals in brackets.", "",
             "## Accuracy by evidence condition", "",
             "| Method | " + " | ".join(COND_NAMES[c] for c in CONDITIONS) + " | Overall |",
             "|---|" + "---:|" * (len(CONDITIONS) + 1)]
    for name, r in m.items():
        cells = [f"{pct(r['by_condition'][c]['acc'])}" for c in CONDITIONS]
        o = r["overall"]
        lines.append(f"| {name} | " + " | ".join(cells) + f" | {pct(o['acc'])} [{pct(o['ci'][0])}–{pct(o['ci'][1])}] (n={o['n']}) |")
    lines += ["", "## Other measures", "",
              "| Method | Macro-F1 (full) | Macro-F1 (metrics only) | Component acc. | Multi-fault hit | Multi-fault both | False alarms | Invalid output | ECE | Conf. right / wrong | Latency (s) | Tokens |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|---:|"]
    for name, r in m.items():
        lines.append(
            f"| {name} | {pct(r['macro_f1_by_condition']['full'])} | {pct(r['macro_f1_by_condition']['metrics_only'])} | "
            f"{pct(r['component_acc'])} | {pct(r['multi_hit']['acc'])} | {pct(r['multi_both'])} | {pct(r['false_alarm_rate'])} | "
            f"{pct(r['invalid_rate'])} | {r['ece']:.3f} | {r['mean_conf_correct']:.2f} / {r['mean_conf_wrong']:.2f} | "
            f"{_num(r['mean_latency_s'], '.1f')} | "
            f"{_num(r['mean_tokens'], '.0f')} |")
    lines += ["", "## Accuracy by fault (all conditions)", "",
              "| Fault | " + " | ".join(m) + " |", "|---|" + "---:|" * len(m)]
    for f in LABELS:
        lines.append(f"| {f} | " + " | ".join(pct(r["by_fault"][f]["acc"]) for r in m.values()) + " |")
    if summary["mcnemar"]:
        lines += ["", "## Paired significance (exact McNemar, same bundles)", "", "| Comparison | n | p-value |", "|---|---:|---:|"]
        for k, v in summary["mcnemar"].items():
            lines.append(f"| {k} | {v['n']} | {v['p']:.4f} |")
    path.write_text("\n".join(lines) + "\n")


def write_latex(summary: dict, path: Path) -> None:
    m = summary["methods"]
    t = [r"% Auto-generated by `python -m rcabench report`. Do not edit by hand.",
         r"\begin{table}[t]", r"\centering", r"\caption{Root-cause accuracy (\%) by evidence condition.}",
         r"\label{tab:accuracy}", r"\begin{tabular}{l" + "r" * (len(CONDITIONS) + 1) + "}", r"\toprule",
         "Method & " + " & ".join(COND_NAMES[c] for c in CONDITIONS) + r" & Overall \\", r"\midrule"]
    for name, r in m.items():
        t.append(tex_name(name) + " & " + " & ".join(pct(r["by_condition"][c]["acc"]) for c in CONDITIONS)
                 + f" & {pct(r['overall']['acc'])}" + r" \\")
    t += [r"\bottomrule", r"\end{tabular}", r"\end{table}", "",
          r"\begin{table}[t]", r"\centering", r"\caption{Secondary measures (\%, except ECE).}", r"\label{tab:secondary}",
          r"\begin{tabular}{lrrrrr}", r"\toprule",
          r"Method & Component & Multi-fault hit & False alarm & Invalid & ECE \\", r"\midrule"]
    for name, r in m.items():
        t.append(f"{tex_name(name)} & {pct(r['component_acc'])} & {pct(r['multi_hit']['acc'])} & "
                 f"{pct(r['false_alarm_rate'])} & {pct(r['invalid_rate'])} & {r['ece']:.3f}" + r" \\")
    t += [r"\bottomrule", r"\end{tabular}", r"\end{table}", "",
          r"\begin{table}[t]", r"\centering", r"\caption{Fault catalogue (ground-truth labels).}", r"\label{tab:faults}",
          r"\begin{tabular}{p{0.3\linewidth}p{0.6\linewidth}}", r"\toprule", r"Label & Injected behaviour \\", r"\midrule"]
    for f in sorted(FAULTS):
        t.append(f"{tex_name(f)} & {tex_name(FAULTS[f].description)}" + r" \\")
    t += [r"no\_incident & Control: harmless 2.2$\times$ traffic spike, nothing broken \\",
          r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    path.write_text("\n".join(t) + "\n")


def write_figures(summary: dict, folder: Path) -> list[Path]:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    folder.mkdir(parents=True, exist_ok=True)
    m = summary["methods"]
    made = []
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False})

    # 1. accuracy by condition, grouped bars with CIs
    fig, ax = plt.subplots(figsize=(6.5, 3.0))
    names = list(m)
    width = 0.8 / max(1, len(names))
    for i, name in enumerate(names):
        accs = [m[name]["by_condition"][c]["acc"] * 100 for c in CONDITIONS]
        lo = [max(0.0, a - m[name]["by_condition"][c]["ci"][0] * 100) for a, c in zip(accs, CONDITIONS)]
        hi = [max(0.0, m[name]["by_condition"][c]["ci"][1] * 100 - a) for a, c in zip(accs, CONDITIONS)]
        xs = [j + (i - (len(names) - 1) / 2) * width for j in range(len(CONDITIONS))]
        ax.bar(xs, accs, width * 0.92, yerr=[lo, hi], capsize=2, label=name, error_kw={"lw": 0.8})
    ax.set_xticks(range(len(CONDITIONS)), [COND_NAMES[c] for c in CONDITIONS])
    ax.set_ylabel("Accuracy (%)")
    ax.set_ylim(0, 105)
    ax.legend(frameon=False, ncol=min(4, len(names)), fontsize=8, loc="lower center", bbox_to_anchor=(0.5, 1.0))
    fig.tight_layout()
    p = folder / "accuracy_by_condition.pdf"
    fig.savefig(p)
    fig.savefig(p.with_suffix(".png"), dpi=200)
    plt.close(fig)
    made.append(p)

    # 2. a confusion matrix per method
    for name, r in m.items():
        labels = LABELS
        preds = labels + ["invalid"]
        grid = [[r["confusion"].get((t, pr), 0) for pr in preds] for t in labels]
        fig, ax = plt.subplots(figsize=(5.2, 4.4))
        ax.imshow(grid, cmap="Greys")
        ax.set_xticks(range(len(preds)), [x.replace("_", " ") for x in preds], rotation=60, ha="right", fontsize=7)
        ax.set_yticks(range(len(labels)), [x.replace("_", " ") for x in labels], fontsize=7)
        ax.set_xlabel("Predicted")
        ax.set_ylabel("True")
        ax.set_title(name, fontsize=9)
        peak = max(max(row) for row in grid) or 1
        for i, row in enumerate(grid):
            for j, v in enumerate(row):
                if v:
                    ax.text(j, i, v, ha="center", va="center", fontsize=6, color="white" if v > peak / 2 else "black")
        fig.tight_layout()
        safe = name.replace(":", "_").replace("/", "_")
        p = folder / f"confusion_{safe}.pdf"
        fig.savefig(p)
        fig.savefig(p.with_suffix(".png"), dpi=200)
        plt.close(fig)
        made.append(p)
    return made


def write_all(summary: dict, out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    write_markdown(summary, out / "summary.md")
    write_latex(summary, out / "tables.tex")
    figs = write_figures(summary, out / "figures")
    return [out / "summary.md", out / "tables.tex", *figs]
